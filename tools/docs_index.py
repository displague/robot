"""
docs_index.py - docs/index.md from the numbered docs' front matter (title, summary, section).

Each docs/NN-*.md starts with a YAML block:

    ---
    title: "39 - Walking with a bag in hand ..."
    summary: "One or two sentences: what it found, and its decisions"
    section: "Skills: wind, bags, chairs, chains"
    ---

The index lists them by section, in number order, with the reference pages after. The mkdocs build runs this
(tools/mkdocs_hooks.py), and the committed docs/index.md is the same file for readers on GitHub.

    python tools/docs_index.py           # write docs/index.md
    python tools/docs_index.py --check   # exit 1 if docs/index.md is stale or a doc lacks front matter
"""
import glob
import os
import re
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
DOCS = os.path.join(os.path.dirname(HERE), "docs")
SECTIONS = [                       # the order sections appear in; a doc naming another section goes last
    "Design and hardware",
    "Simulation, balance and walking",
    "Drives, mass and energy",
    "Skills: wind, bags, chairs, chains",
    "Learned control",
]
REFERENCE = [
    ("decisions.md", "Decision log", "What we chose and why (D-nnn); revisit when a test disagrees"),
    ("prompt-log.md", "Prompt log", "Every prompt that produced a set of work, verbatim (P-nnn), with what it produced"),
    ("releases.md", "Releases", "Each tag's notes, visuals and assets"),
    ("references.md", "References", "External projects to borrow test scenarios and tooling from"),
]


def front_matter(path):
    text = open(path, encoding="utf-8").read()
    m = re.match(r"---\r?\n(.*?)\r?\n---\r?\n", text, re.S)
    if not m:
        raise SystemExit("%s has no front matter (title, summary, section)" % os.path.relpath(path))
    fm = yaml.safe_load(m.group(1))
    for k in ("title", "summary", "section"):
        if not fm.get(k):
            raise SystemExit("%s: front matter lacks %r" % (os.path.relpath(path), k))
    return fm


def render(docs_dir=DOCS):
    docs = []
    for p in sorted(glob.glob(os.path.join(docs_dir, "[0-9][0-9]-*.md"))):
        fm = front_matter(p)
        docs.append((os.path.basename(p), fm))
    order = SECTIONS + sorted({fm["section"] for _, fm in docs} - set(SECTIONS))
    out = ["# Robot docs", "",
           "A home-printable, fishing-line tendon humanoid, so far entirely in simulation. The design and the "
           "repository map are in the [README](https://github.com/displague/robot#readme). Each doc below is an "
           "experiment or a design note; its \"Not yet\" and \"Next\" sections are the backlog.", "",
           "<!-- generated by tools/docs_index.py from each doc's front matter; edit the docs, not this file -->", ""]
    for sec in order:
        rows = [(n, fm) for n, fm in docs if fm["section"] == sec]
        if not rows:
            continue
        out += ["## " + sec, "", "| Doc | Summary |", "| --- | --- |"]
        for n, fm in rows:
            out.append("| [%s](%s) | %s |" % (fm["title"].replace("|", "\\|"), n, fm["summary"].replace("|", "\\|")))
        out.append("")
    out += ["## Reference", "", "| Page | What |", "| --- | --- |"]
    out += ["| [%s](%s) | %s |" % (t, n, s) for n, t, s in REFERENCE if os.path.exists(os.path.join(docs_dir, n))]
    return "\n".join(out) + "\n"


def write(docs_dir=DOCS):
    """Write docs/index.md if it changed; return True if it did (so mkdocs serve does not loop)."""
    path = os.path.join(docs_dir, "index.md")
    new = render(docs_dir)
    old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
    if old is not None and old.replace("\r\n", "\n") == new:
        return False
    open(path, "w", encoding="utf-8", newline="\n").write(new)
    return True


if __name__ == "__main__":
    if "--check" in sys.argv:
        path = os.path.join(DOCS, "index.md")
        cur = open(path, encoding="utf-8").read().replace("\r\n", "\n") if os.path.exists(path) else ""
        if cur != render():
            raise SystemExit("docs/index.md is stale: run python tools/docs_index.py")
        print("docs/index.md is current")
    else:
        print("wrote docs/index.md" if write() else "docs/index.md unchanged")
